def team_for_slice(idx, slice_id, retry=0):
    """Keep retry identity inside CDPA's existing 48-character team-base limit."""
    prefix = f'g6-selfrepair-{idx+1:02d}-'
    suffix = f'-retry{retry}' if retry else ''
    room = 48 - len(prefix) - len(suffix)
    if room < 8:
        raise RuntimeError('Self-repair team name has insufficient identity space')
    slug = str(slice_id)[:room].rstrip('-_')
    if not slug:
        raise RuntimeError('Self-repair slice ID is empty')
    return prefix + slug + suffix


def start_slice(config, state, board, part):
    idx = state['next_index']
    retry = int(state.get('slice_retries', {}).get(part['id'], 0))
    team = team_for_slice(idx, part['id'], retry)
    matching = [item for item in board if item.get('team') == team]
    if len(matching) > 1:
        raise RuntimeError('Duplicate team identity: ' + team)
    # An operator may have already stopped the original TeamTask, including
    # after CDPA cleanup. Never adopt that accepted Send as a fresh execution.
    # Require exact durable Stop evidence and use a distinct idempotency key.
    while matching and matching[0].get('status') == 'STOPPED':
        previous = matching[0]
        previous_id = str(previous.get('task_id') or '')
        if not previous_id:
            raise RuntimeError('Stopped team has no task ID; proof unavailable')
        detail = api('GET', '/api/tasks/' + previous_id)
        if not verified_applied_stop(previous, detail):
            raise RuntimeError('Stopped team has no verified applied stop/cleanup proof')
        if retry >= 2:
            raise RuntimeError('Stopped team retry budget exhausted; investigate terminal root cause')
        archived = state.setdefault('archived_blocked', [])
        if previous_id not in archived:
            archived.append(previous_id)
        retry += 1
        state.setdefault('slice_retries', {})[part['id']] = retry
        team = team_for_slice(idx, part['id'], retry)
        matching = [item for item in board if item.get('team') == team]
        if len(matching) > 1:
            raise RuntimeError('Duplicate retry team identity: ' + team)
    if matching and matching[0].get('status') in ('BLOCKED','PAUSED','DONE','FAILED','CANCELLED'):
        raise RuntimeError('Prior team requires explicit reconciliation; never reuse terminal/blocked Send')
    if not matching:
        archived = set(state.get('archived_blocked', []))
        others = [x for x in board if str(x.get('team', '')).startswith('g6-selfrepair-')
                  and x.get('status') not in ('DONE','STOPPED','FAILED','CANCELLED')
                  and not (x.get('task_id') in archived and x.get('status') == 'BLOCKED')]
        if others:
            raise RuntimeError('Another active self-repair task: ' + str(others[0].get('team')))
    state['active'] = state.get('active') or {'slice_id':part['id'], 'team':team,
        'task_id':None, 'command_id':None, 'submitted_at':now(), 'status':'pre_submit', 'action':'none'}
    state['phase'] = 'SUBMITTING'; save(state)
    if matching:
        state['active']['task_id'] = matching[0].get('task_id')
    else:
        task_prompt = make_prompt(config, part, state)
        if part['id'] == '08-real-browser' and retry:
            task_prompt += (
                '\nNEW 08 RECOVERY SOLO: The earlier 08 task had an accepted completed '
                'Send and a valid PAUSE route; it was subsequently STOPPED with exact '
                'applied Stop and CLEARED cleanup. Do not reopen, retry or resend its '
                'accepted turn. Start only a new owned 9202 conversation. '
                'Read the predecessor receipt 08-real-browser.json, receipt 07-regression.json '
                '(broad 2020 passed), and the G6 model attestation at '
                '.runtime/self-repair/08-real-browser-model-attestation.json as '
                'historical evidence, NOT as model proof for this NEW task. '
                'Check this task exact model_gate events in .runtime/action-events.jsonl '
                'before and after Send, inspect the owned tab model UI (High/Extra High), '
                'inspect its own requests.json accepted Send once and terminal DOM, '
                'then verify clean noninterference/health. Never declare release PASS '
                'from API health or offline pytest alone.'
            )
        payload = {'workflow_mode':'solo','role':'DEV','requested_team':team,
            'repository':str(ROOT), 'browser_endpoint_id':config['browser_endpoint_id'],
            'goal':'Complete G6 CDPA Gate C safely: ' + part['title'],
            'task':task_prompt}
        key_name = 'create' if retry == 0 else f'create-retry{retry}'
        reply = api('POST','/api/tasks',payload, key_for(config,idx,key_name))
        state['active']['task_id'] = reply.get('task_id')
        state['active']['command_id'] = reply.get('command_id')
    state['phase']='ACTIVE';state['reason']='Created or reconciled one Solo TeamTask'
    save(state)

def verified_applied_stop(board_item, detail):
    """Only a durable applied Stop can retire a browser-backed writer.

    CDPA cleanup changes active_action to 'cleared'; the browser snapshot
    remains historical, so require positive CLEARED evidence in that case.
    """
    if (board_item.get('task_id') != detail.get('task_id')
            or board_item.get('team') != detail.get('team')
            or board_item.get('status') != 'STOPPED'
            or detail.get('status') != 'STOPPED'
            or board_item.get('stop_reason') != detail.get('stop_reason')):
        return False
    reason = str(detail.get('stop_reason') or '')
    if not reason or not any(
        item.get('action') == 'stop' and item.get('status') == 'applied'
        and item.get('reason') == reason
        for item in detail.get('controls') or []
    ):
        return False
    if board_item.get('active_action') == 'cleared':
        cleanup = detail.get('cleanup') or board_item.get('cleanup') or {}
        return (detail.get('active_action') == 'cleared'
                and cleanup.get('state') == 'CLEARED'
                and cleanup.get('status_before') == 'STOPPED'
                and bool(cleanup.get('verified_empty_at')))
    browser = detail.get('browser_control') or board_item.get('browser_control') or {}
    return (board_item.get('active_action') == 'stopped'
            and detail.get('active_action') == 'stopped'
            and browser.get('stop_visible') is False
            and browser.get('retry_visible') is False)


def verified_code_receipt(active, *, allow_blocked=False):
    receipt = load(HERE / 'receipts' / (active['slice_id'] + '.json'), {})
    if (not isinstance(receipt, dict)
            or receipt.get('slice_id') != active['slice_id']
            or receipt.get('task_id') != active['task_id']
            or receipt.get('status') not in ({'PASS', 'BLOCKED'} if allow_blocked else {'PASS'})
            or not receipt.get('evidence')
            or not any(
                isinstance(t, dict) and 'pytest' in str(t.get('command', '')).lower()
                and ('PASS' in str(t.get('result', '')).upper()
                     or 'passed' in str(t.get('result', '')).lower())
                for t in receipt.get('tests') or [])):
        raise RuntimeError('Missing exact verified code-only receipt')
    return receipt


def process_active(config, state, board):
    active = state['active']
    matches = [x for x in board if x.get('team') == active['team']]
    if not matches and active.get('task_id') and len(str(active.get('team') or '')) > 48:
        # Older supervisor submissions were truncated by CDPA to 48 characters.
        # Recover only the exact already-admitted task; never adopt another Send.
        normalized = str(active['team'])[:48].rstrip('-_')
        matches = [x for x in board
                   if x.get('team') == normalized and x.get('task_id') == active['task_id']]
        if len(matches) == 1:
            active['team'] = normalized
    if len(matches) > 1:
        raise RuntimeError('Duplicated task team; do not proceed')
    if not matches:
        state['phase']='RECONCILE';state['reason']='Submitted command but task not yet projected; never resubmit blindly'
        return
    x=matches[0]
    if active.get('task_id') and x.get('task_id') != active['task_id']:
        raise RuntimeError('Task id drift; stop for reconciliation')
    active['task_id']=x.get('task_id')
    active['status']=x.get('status')
    active['action']=x.get('active_action')
    status=str(x.get('status') or '')
    if status == 'DONE' and active['slice_id'] == '11-final-real-cdp':
        receipt = verify_receipt(active)
        compare = load(
            ROOT / '.runtime' / 'self-repair' / '11-final-tabs-compare.json',
            {},
        )
        if (
            compare.get('slice_id') != '11-final-real-cdp'
            or compare.get('task_id') != active['task_id']
            or compare.get('status') != 'PASS'
            or compare.get('unrelated_unchanged') is not True
            or not compare.get('owned_page_id')
            or int(compare.get('send_click_count') or 0) != 1
            or compare.get('model_gate_before_fill') is not True
            or compare.get('model_gate_before_send') is not True
            or int(compare.get('retry_or_repair_count') or 0) != 0
            or compare.get('terminal_route') != 'DONE'
        ):
            state['phase'] = 'ACTIVE'
            state['reason'] = 'Final live-CDP DONE awaits exact coordinator tab comparison'
        else:
            state['completed'].append({
                'slice_id': active['slice_id'],
                'task_id': active['task_id'],
                'evidence': 'Final live-CDP DONE plus coordinator before/after noninterference PASS',
            })
            state['next_index'] += 1
            state['active'] = None
            state['phase'] = 'IDLE'
            state['reason'] = 'Verified final live-CDP DONE, receipt and tab comparison'
    elif status == 'DONE' and active['slice_id'] == '16-final-release-evidence':
        detail = api('GET', '/api/tasks/' + active['task_id'])
        cleanup = detail.get('cleanup') or {}
        receipt = load(HERE / 'receipts' / '16-final-release-evidence.json', {})
        if (detail.get('task_id') != active['task_id'] or detail.get('team') != active['team']
                or detail.get('status') != 'DONE' or detail.get('active_action') != 'cleared'
                or cleanup.get('state') != 'CLEARED' or not cleanup.get('verified_empty_at')
                or receipt.get('task_id') != active['task_id']
                or receipt.get('slice_id') != active['slice_id']
                or receipt.get('status') != 'BLOCKED'
                or receipt.get('release_verdict') != 'NOT_ACCEPTED'
                or not receipt.get('evidence')):
            raise RuntimeError('Final review DONE/CLEARED and BLOCKED receipt mismatch')
        state['completed'].append({'slice_id': active['slice_id'], 'task_id': active['task_id'],
                                   'evidence': 'Review completed; release proof missing'})
        state['next_index'] += 1
        state['active'] = None
        state['pi_attempts'] = 0
        state['phase'] = 'RELEASE_REVIEW'
        state['release'] = 'NOT_ACCEPTED'
        state['reason'] = 'Final review retired without release acceptance'
    elif status == 'DONE':
        receipt=verify_receipt(active)
        state['completed'].append({'slice_id':active['slice_id'],'task_id':active['task_id'],
                                   'evidence':str(receipt['evidence'])[:200]})
        state['next_index']+=1;state['active']=None
        state['phase']='IDLE';state['reason']='Verified terminal DONE and receipt'
    elif (status == 'BLOCKED' and active['slice_id'] == '01-inventory'
          and x.get('block_code') == 'response_terminal_missing'
          and x.get('active_action') == 'blocked'
          and not (x.get('browser_control') or {}).get('stop_visible', True)):
        receipt = load(HERE / 'receipts' / '01-inventory.json', {})
        findings = (receipt.get('evidence') or {}).get('ordered_minimum_fixes') if isinstance(receipt, dict) else None
        if (receipt.get('task_id') == active['task_id'] and receipt.get('status') == 'BLOCKED'
                and isinstance(findings, list) and findings):
            state.setdefault('archived_blocked', []).append(active['task_id'])
            state['completed'].append({'slice_id': active['slice_id'], 'task_id': active['task_id'],
                                       'evidence': 'Audit finished with findings; terminal DOM blocker remains open'})
            state['next_index'] += 1
            state['active'] = None
            state['phase'] = 'IDLE'
            incident(state, 'Prior Solo remains BLOCKED; next slice repairs terminal DOM detection in fresh conversation')
        else:
            queue_pi(state, 'Inventory diagnostic did not produce verifiable findings')
    elif (status == 'BLOCKED' and active['slice_id'] == '01b-terminal-recovery'
          and x.get('block_code') == 'provider_challenge'
          and x.get('active_action') == 'blocked'
          and not (x.get('browser_control') or {}).get('stop_visible', True)):
        recovery_path = ROOT / '.runtime' / 'self-repair' / 'browser9202-restore-report.json'
        recovery = load(recovery_path, {})
        next_slice = config['slices'][state['next_index'] + 1] if state['next_index'] + 1 < len(config['slices']) else {}
        submitted_at = dt.datetime.fromisoformat(active['submitted_at']).timestamp()
        fresh_recovery = recovery_path.is_file() and recovery_path.stat().st_mtime > submitted_at
        if (next_slice.get('id') == '01c-terminal-fresh-retry'
                and isinstance(recovery, dict) and len(recovery.get('results') or []) >= 1
                and fresh_recovery):
            state.setdefault('archived_blocked', []).append(active['task_id'])
            state.setdefault('blocked_history', []).append({
                'slice_id': active['slice_id'], 'task_id': active['task_id'],
                'status': 'BLOCKED', 'block_code': 'provider_challenge',
                'next_action': 'one fresh isolated recovery Solo; never resend the accepted turn'})
            state['next_index'] += 1
            state['active'] = None
            state['phase'] = 'IDLE'
            incident(state, 'Bounded 9202 restart verified; original accepted Send stays BLOCKED, fresh recovery queued')
        else:
            state['phase'] = 'NEEDS_PI'
            incident(state, 'Missing verified G6 restart or wrong one-shot retry slice; no unsafe retry')
    elif (status == 'BLOCKED' and x.get('block_code') == 'response_terminal_missing'
          and active['slice_id'] != '08-real-browser'
          and x.get('active_action') == 'blocked'
          and x.get('availability') == 'offline'
          and (x.get('browser_control') or {}).get('stop_visible') is False
          and (x.get('browser_control') or {}).get('retry_visible') is False):
        # ChatGPT can complete filesystem work but render an empty final assistant
        # shell. A verified code receipt can advance the *campaign slice*, never
        # the BLOCKED browser turn or real-CDP release gate.
        receipt = load(HERE / 'receipts' / (active['slice_id'] + '.json'), {})
        tests = receipt.get('tests', []) if isinstance(receipt, dict) else []
        verified_test = any(
            isinstance(t, dict) and 'pytest' in str(t.get('command', '')).lower()
            and ('PASS' in str(t.get('result', '')).upper() or 'passed' in str(t.get('result', '')).lower())
            for t in tests
        )
        if (receipt.get('slice_id') == active['slice_id']
                and receipt.get('task_id') == active['task_id']
                and receipt.get('status') == 'PASS'
                and verified_test and receipt.get('evidence')):
            state.setdefault('archived_blocked', []).append(active['task_id'])
            state.setdefault('blocked_history', []).append({
                'slice_id': active['slice_id'], 'task_id': active['task_id'],
                'status': 'BLOCKED', 'block_code': 'response_terminal_missing',
                'next_action': 'code-only proof accepted, real browser terminal unresolved'})
            state['completed'].append({
                'slice_id': active['slice_id'], 'task_id': active['task_id'],
                'task_terminal_status': 'BLOCKED',
                'evidence': 'Tests and artifact verified; real browser route remains unverified'})
            state['next_index'] += 1
            state['active'] = None
            state['pi_attempts'] = 0
            state['phase'] = 'IDLE'
            incident(state, 'Artifact-backed code slice complete; original Send remains BLOCKED, no replay')
        else:
            queue_pi(state, 'Missing verified code receipt; blocked task retained')
    elif (status == 'STOPPED' and active['slice_id'] == '06-async-wait'
          and str(x.get('stop_reason') or '') ==
          'Pi recovery: blocked permission_review with accepted Send preserved; stop before CDPA runtime reload'):
        # One proven code-only result. The accepted browser turn was explicitly
        # stopped and remains NOT_ACCEPTED; only a new slice may send again.
        detail = api('GET', '/api/tasks/' + active['task_id'])
        if not verified_applied_stop(x, detail):
            queue_pi(state, 'Solo 06 Stop/cleanup proof missing; do not replay accepted Send')
        else:
            try:
                receipt = verified_code_receipt(active, allow_blocked=True)
                if receipt['status'] != 'BLOCKED':
                    raise RuntimeError('Solo 06 recovery requires exact BLOCKED receipt')
            except RuntimeError as exc:
                queue_pi(state, str(exc))
            else:
                state.setdefault('archived_blocked', []).append(active['task_id'])
                state.setdefault('blocked_history', []).append({
                    'slice_id': active['slice_id'], 'task_id': active['task_id'],
                    'status': 'STOPPED', 'stop_reason': str(x['stop_reason']),
                    'receipt_status': 'BLOCKED',
                    'next_action': 'code-only result accepted; real browser acceptance remains unverified'})
                state['completed'].append({
                    'slice_id': active['slice_id'], 'task_id': active['task_id'],
                    'task_terminal_status': 'STOPPED', 'receipt_status': 'BLOCKED',
                    'evidence': '46 focused checks proved async code, browser terminal unresolved'})
                state['next_index'] += 1
                state['active'] = None
                state['pi_attempts'] = 0
                state['phase'] = 'IDLE'
                incident(state, 'Reconciled exact applied Solo 06 Stop and CLEARED cleanup; no replay')
    elif status == 'STOPPED' and active['slice_id'] == '11-final-real-cdp':
        # Strict single-hop final acceptance must never be resumed/retried once
        # a Send was accepted and a provider permission prompt blocked DONE.
        # Retire only its own officially stopped and CLEARED browser writer;
        # a separate read-only release review owns the next step.
        reason = str(x.get('stop_reason') or '')
        valid_reason = reason == (
            'G6 final acceptance 11 failed closed: BLOCKED permission_review '
            'after one accepted Send; direct DONE cannot be proven; preserve '
            'accepted ledger and forbid Retry/Resume'
        )
        detail = api('GET', '/api/tasks/' + active['task_id']) if valid_reason else {}
        cleanup = detail.get('cleanup') or {}
        try:
            receipt = verified_code_receipt(active, allow_blocked=True)
            next_part = (config['slices'][state['next_index'] + 1]
                         if state['next_index'] + 1 < len(config['slices']) else {})
            if (receipt.get('status') != 'BLOCKED'
                    or str(receipt.get('release') or 'NOT_ACCEPTED') != 'NOT_ACCEPTED'
                    or next_part.get('id') != '12-final-release-review'
                    or not valid_reason
                    or not verified_applied_stop(x, detail)
                    or detail.get('active_action') != 'cleared'
                    or cleanup.get('state') != 'CLEARED'
                    or cleanup.get('status_before') != 'STOPPED'
                    or not cleanup.get('verified_empty_at')):
                raise RuntimeError('Final 11 Stop/CLEARED/receipt/review contract is unproven')
        except RuntimeError as exc:
            queue_pi(state, str(exc))
        else:
            archived = state.setdefault('archived_blocked', [])
