def pi_command(config, mode, state):
    """Run the pinned Luna/High Pi coordinator with bounded time; never guess success."""
    prompt = (
        'You are the sole G6 CDPA coordinator. Work ONLY in E:\\git-project\\cdpa on G6. '
        'Read workflows/self-repair/MISSION.md, PROGRESS.md, slices.json and '
        '.agents/skills/cdpa-self-repair/SKILL.md, AGENTS.md and the R11 contract. '
        'We use one Solo TeamTask at a time, with durable idempotent commands. '
        'Never manipulate unrelated tabs or blindly retry an ambiguous Send. '
        'Current state JSON follows: ' + json.dumps(state, ensure_ascii=True) + '\n'
    )
    if mode == 'recovery':
        prompt += ('Diagnose the exact blocked/stalled state using source and current local evidence. '
                   'Top operational priority: stop the CDPA task, then reload G6 CDPA API/dashboard/worker '
                   'immediately when stale or SOURCE_DRIFT; the ChatGPT browser survives the reload. '
                   'Do not wait on browser UI or rerun an accepted Send; use command ledger and receipts '
                   'to reconcile and dispatch a fresh subsequent slice. '
                   'Apply only a minimal root-cause code/test fix if required. '
                   'Record reload outcome and recovery evidence in workflows/self-repair/PI_RECOVERY.md. '
                   'Finish with token PI_RECOVERY_DONE or PI_RECOVERY_HOLD.')
        tools = 'read,bash,edit,write'
    else:
        prompt += ('Inspect next slice and scheduling readiness, then return exactly '
                   'PI_SLICE_APPROVED if safe, otherwise PI_SLICE_HOLD. Do not modify files.')
        tools = 'read'
    model = config.get('pi_model', 'cliproxy-g8/gpt-5.6-luna')
    entry = Path(os.environ['APPDATA']) / 'npm' / 'node_modules' / '@earendil-works' / 'pi-coding-agent' / 'dist' / 'bundle' / 'cli.js'
    if not entry.is_file():
        return False, 'Pi Coding CLI entrypoint unavailable on G6'
    # Campaign memory lives in MISSION/PROGRESS/receipts. Replaying the multi-MB
    # Pi session on each scheduled run caused repeated invocation timeouts.
    cmd = ['node.exe', str(entry), '-p', '--model', model, '--thinking', 'high',
           '--offline', '--no-session', '--no-approve', '--no-context-files',
           '--no-prompt-templates', '--no-skills', '--no-mcp', '--no-extensions',
           '--tools', tools, prompt]
    try:
        result = subprocess.run(cmd, cwd=str(ROOT), stdin=subprocess.DEVNULL,
                                capture_output=True, text=True,
                                encoding='utf-8', errors='replace', timeout=20,
                                creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
        if result.returncode != 0:
            return False, 'Pi exit ' + str(result.returncode) + ': ' + result.stderr[-280:]
        output = result.stdout.strip()
        token = 'PI_RECOVERY_DONE' if mode == 'recovery' else 'PI_SLICE_APPROVED'
        return token in output.split(), output[-350:]
    except (subprocess.TimeoutExpired, OSError) as e:
        return False, type(e).__name__ + ': ' + str(e)[:250]

def queue_pi(state, reason):
    state['phase'] = 'NEEDS_PI'
    incident(state, reason)

def read_status(state):
    return {'campaign':state['campaign'], 'phase':state['phase'],
            'next_index':state['next_index'], 'active':state.get('active'),
            'reason':state.get('reason'), 'release':state.get('release')}

def resume_after_recovery(config, state):
    """Resume the same durable task only if CDPA's own control contract admits it."""
    active = state.get('active')
    if not active or not active.get('task_id'):
        state['phase'] = 'NEEDS_PI'
        incident(state, 'Recovery has no exact task id')
        return
    detail = api('GET', '/api/tasks/' + active['task_id'])
    if detail.get('team') != active['team']:
        raise RuntimeError('Recovery team identity changed')
    if detail.get('status') in ('DONE', 'RUNNING', 'WAITING'):
        state['phase'] = 'ACTIVE'
        state['reason'] = 'Task already progressed; reconcile without resend'
        return
    if detail.get('status') not in ('BLOCKED', 'PAUSED'):
        state['phase'] = 'NEEDS_PI'
        incident(state, 'Task terminal or unknown; never blindly resume')
        return
    eligibility = detail.get('control_eligibility') or {}
    resume = eligibility.get('resume') or {}
    if not resume.get('eligible'):
        state['phase'] = 'NEEDS_PI'
        incident(state, 'CDPA refuses Resume: ' + str(resume.get('reason')))
        return
    attempt = state.get('pi_attempts', 0)
    reply = api('POST', '/api/tasks/resume', {'team':active['team']},
                key_for(config, state['next_index'], 'resume-' + str(attempt)))
    active['resume_command_id'] = reply.get('command_id')
    state['phase'] = 'ACTIVE'
    state['reason'] = 'Reused same task after Pi recovery; send ledger remains authoritative'


def maybe_stop_stale_code_slice(config, state, item):
    """Retire only an idle, receipt-backed browser writer via CDPA's Stop control."""
    active = state.get('active') or {}
    browser = item.get('browser_control') or {}
    if (active.get('stop_command_id') or active.get('slice_id') == '08-real-browser'
            or item.get('status') != 'RUNNING'
            or item.get('active_action') != 'wait_response'
            or any(browser.get(k) is not False
                   for k in ('stop_visible', 'retry_visible', 'composer_nonempty'))):
        return
    try:
        seen = dt.datetime.fromisoformat(str(item.get('effective_activity_at') or ''))
        if seen.tzinfo is None:
            seen = seen.replace(tzinfo=dt.timezone.utc)
    except ValueError:
        return
    if (dt.datetime.now(dt.timezone.utc) - seen).total_seconds() < max(
            1800, int(config.get('stall_seconds', 1200))):
        return
    try:
        receipt = verify_receipt(active)
    except RuntimeError:
        return
    if not any(
        isinstance(t, dict) and 'pytest' in str(t.get('command', '')).lower()
        and ('PASS' in str(t.get('result', '')).upper()
             or 'passed' in str(t.get('result', '')).lower())
        for t in receipt['tests']
    ):
        return
    detail = api('GET', '/api/tasks/' + active['task_id'])
    current = detail.get('browser_control') or {}
    if (detail.get('task_id') != active['task_id']
            or detail.get('team') != active['team']
            or detail.get('status') != 'RUNNING'
            or detail.get('active_action') != 'wait_response'
            or (detail.get('active_hop') or {}).get('state') != 'waiting'
            or not (detail.get('control_eligibility') or {}).get('stop', {}).get('eligible')
            or not isinstance(detail.get('version'), int)
            or any(current.get(k) is not False
                   for k in ('stop_visible', 'retry_visible', 'composer_nonempty'))):
        return
    reason = (
        'G6 self-repair stale empty assistant: verified code receipt PASS, '
        'accepted Send once, no Stop or Retry for 30+ min; preserve ledger'
    )
    response = api(
        'POST', '/api/tasks/' + active['task_id'] + '/controls',
        {'action': 'stop', 'role': detail.get('active_role') or 'DEV',
         'reason': reason, 'confirmed': True,
         'expected_task_version': detail['version']},
        key_for(config, state['next_index'], 'stale_empty_assistant_stop'),
    )
    active['stop_command_id'] = response.get('command_id')
    state['reason'] = 'Official Stop requested; awaiting applied control evidence'


def reload_g6_runtime(state):
    """Reload G6 CDPA immediately, preserving browser and ledger."""
    script = HERE / 'reload_cdpa.ps1'
    if not script.is_file():
        raise RuntimeError('CDPA reload script missing')
    result = subprocess.run(
        ['powershell.exe', '-NoProfile', '-NonInteractive', '-ExecutionPolicy',
         'Bypass', '-File', str(script)],
        cwd=str(ROOT), stdin=subprocess.DEVNULL, capture_output=True,
        text=True, encoding='utf-8', errors='replace', timeout=100,
        creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0),
    )
    if result.returncode == 2 and result.stdout.strip() == 'RELOAD_ALREADY_IN_PROGRESS':
        # reload.lock has a different live owner; an overlapping scheduler tick
        # must not convert a legitimate in-flight reload into Pi exhaustion.
        state['reason'] = 'CDPA reload already in progress; verify health next tick'
        return
    if result.returncode != 0 or 'RELOAD_OK' not in result.stdout:
        raise RuntimeError('G6 CDPA reload failed: ' + (result.stderr or result.stdout)[-450:])
    state['reason'] = 'CDPA reloaded; reconcile existing task and continue next tick'


def tick(config, state):
    try:
        health = check_environment(config, allow_source_drift=True)
        board = api('GET','/api/tasks').get('items', [])
    except Exception as error:
        state['phase'] = 'RELOADING'
        save(state)
        try:
            reload_g6_runtime(state)
        except Exception as exc:
            queue_pi(state, 'CDPA unavailable; immediate reload failed: ' + str(error) + '; ' + str(exc))
        else:
            state['phase'] = 'ACTIVE' if state.get('active') else 'IDLE'
        return
    archived = set(state.get('archived_blocked', []))
    for old in board:
        if (old.get('task_id') in archived
                and old.get('status') not in ('BLOCKED','STOPPED','FAILED','CANCELLED','DONE')):
            # This is an ownership violation, not a failed HTTP/worker check.
            # A restart cannot resolve a resurrected accepted Send.
            queue_pi(state, 'Archived blocked task resumed concurrently: '
                     + str(old.get('task_id')))
            return
    if health.get('worker_source_drift', {}).get('drifted'):
        state['phase'] = 'RELOADING'
        save(state)
        try:
            reload_g6_runtime(state)
        except Exception as exc:
            queue_pi(state, 'Immediate CDPA reload failed: ' + str(exc))
        else:
            state['phase'] = 'ACTIVE' if state.get('active') else 'IDLE'
        return
    if state.get('active'):
        old = dict(state['active'])
        process_active(config, state, board)
        active = state.get('active')
        if active and state['phase'] == 'ACTIVE':
            marker = next((x.get('timeline_total') for x in board if x.get('team') == active['team']), None)
            sig = f"{active.get('status')}:{active.get('action')}:{marker}"
            if sig != old.get('signature'):
                active['signature'] = sig
                active['progress_at'] = now()
                active.pop('stall_reload_sig', None)
            elif active.get('progress_at'):
                elapsed = dt.datetime.now(dt.timezone.utc) - dt.datetime.fromisoformat(active['progress_at'])
                if elapsed.total_seconds() > config.get('stall_seconds',1200):
                    if active.get('stall_reload_sig') == sig:
                        queue_pi(state, 'Task still stalled after one CDPA reload; '
                                 'reconcile existing accepted Send before next action')
                        return
                    # Operator priority: reload CDPA rather than wait for a hung
                    # ChatGPT response. The browser is not part of the restart.
                    state['phase'] = 'RELOADING'
                    save(state)
                    try:
                        reload_g6_runtime(state)
                    except Exception as exc:
                        queue_pi(state, 'Stalled CDPA reload failed: ' + str(exc))
                    else:
                        active['stall_reload_sig'] = sig
                        active['progress_at'] = now()
                        state['phase'] = 'ACTIVE'
                    return
            item = next((x for x in board if x.get('team') == active['team']), None)
            if item:
                maybe_stop_stale_code_slice(config, state, item)
        return
    if state.get('next_index',0) >= len(config['slices']):
        state['phase'] = 'RELEASE_REVIEW'
        state['reason'] = 'All slices have receipts; independent release gates still required'
        final_slice = config['slices'][-1]['id'] if config.get('slices') else ''
        final = load(HERE / 'receipts' / (final_slice + '.json'), {})
        if (
            final.get('slice_id') == final_slice
            and final.get('status') == 'PASS'
            and final.get('release_verdict') == 'PASS'
            and final.get('full_regression') == 'PASS'
            and final.get('real_cdp') == 'PASS'
        ):
            state['phase']='COMPLETE'
            state['release']='PASS'
            state['reason']='Final independent receipt reports all accepted release gates PASS'
        return
    if state['phase'] in ('STOPPED','COMPLETE','MANUAL_HOLD'):
        return
    idx = state['next_index']
    part = config['slices'][idx]
    # The user's fixed bounded work plan is pre-authorized. A temporarily offline
    # Pi must not prevent safe deterministic successor admission after a PASS.
    # Pi is mandatory for diagnosis/reprioritization of unexpected blockers.
    start_slice(config,state,board,part)

def stopped_real_browser_ready(candidate, receipt):
    """Only re-enter the deterministic reducer after a proven terminal Stop."""
    if (candidate.get('slice_id') != '08-real-browser'
            or receipt.get('slice_id') != '08-real-browser'
            or receipt.get('task_id') != candidate.get('task_id')
            or receipt.get('status') != 'BLOCKED'
            or not candidate.get('task_id')):
        return False
    try:
        live = api('GET', '/api/tasks/' + candidate['task_id'])
    except Exception:
        return False
    return (live.get('task_id') == candidate['task_id']
            and live.get('team') == candidate.get('team')
            and live.get('status') == 'STOPPED')


def supervise_once():
    config = load(CONFIG)
    LOCK.parent.mkdir(parents=True, exist_ok=True)
    with LOCK.open('a+b') as lock:
        lock.seek(0)
        if not lock.read(1):
            lock.write(b'1'); lock.flush()
        lock.seek(0)
        try:
            msvcrt.locking(lock.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError:
            print('Supervisor already running; skip overlapping scheduled tick')
            return
        try:
            state = load(STATE, new_state(config))
            if state.get('campaign') != config['campaign_id']:
                raise RuntimeError('Campaign identity mismatch')
            receipt = load(HERE / 'receipts' / '01-inventory.json', {})
            recovery_file = ROOT / '.runtime' / 'self-repair' / 'browser9202-restore-report.json'
            inventory_ready = (
                (state.get('active') or {}).get('slice_id') == '01-inventory'
                and isinstance(receipt, dict) and receipt.get('status') == 'BLOCKED'
                and isinstance((receipt.get('evidence') or {}).get('ordered_minimum_fixes'), list)
            )
            challenge_recovered = (
                (state.get('active') or {}).get('slice_id') == '01b-terminal-recovery'
                and recovery_file.is_file()
            )
            candidate = state.get('active') or {}
            code_receipt = load(
                HERE / 'receipts' / (candidate.get('slice_id', '') + '.json'), {})
            code_ready = (
                candidate.get('slice_id') is not None
                and code_receipt.get('slice_id') == candidate.get('slice_id')
                and code_receipt.get('task_id') == candidate.get('task_id')
                and (
                    (candidate.get('slice_id') != '08-real-browser'
                     and (code_receipt.get('status') == 'PASS'
                          or (candidate.get('slice_id') in (
                                  '06-async-wait', '11-final-real-cdp',
                                  '12-final-release-review', '13-allow-reacceptance',
                                  '14-release-recheck', '15-real-terminal-reacceptance',
                                  '15b-fresh-terminal-proof', '16-final-release-evidence')
                              and code_receipt.get('status') == 'BLOCKED')))
                    or stopped_real_browser_ready(candidate, code_receipt)
                )
            )
            if state.get('phase') in ('NEEDS_PI', 'RECOVERY_EXHAUSTED', 'RECOVERY_REVIEW'):
                # Reload-first watchdog must remain active even when Pi's
                # recovery budget is exhausted. Never restart Chrome.
                try:
                    health = api('GET', '/health')
                    unhealthy = (not all(health.get(k) for k in ('ok', 'worker_online', 'worker_ready', 'worker_runtime_ready', 'worker_command_loop_ready'))
                                 or health.get('worker_source_drift', {}).get('drifted'))
                except Exception:
                    unhealthy = True
                if unhealthy:
                    reload_g6_runtime(state)
                    save(state)
                    return
            if state.get('phase') in ('NEEDS_PI', 'RECOVERY_EXHAUSTED', 'RECOVERY_REVIEW') and (inventory_ready or challenge_recovered or code_ready):
                tick(config, state)
            elif state.get('phase') == 'NEEDS_PI':
                if state.get('pi_attempts', 0) >= config.get('max_recovery_attempts', 2):
                    state['phase'] = 'RECOVERY_EXHAUSTED'
                    incident(state, 'Pi recovery budget reached; retain task and review new evidence next tick')
                else:
                    last = state.get('pi_last_try', '')
                    recent = bool(last) and (dt.datetime.now(dt.timezone.utc)-dt.datetime.fromisoformat(last)).total_seconds() < 900
                    if not recent:
                        state['pi_last_try']=now();save(state)
                        ok, output = pi_command(config, 'recovery', state)
                        state['pi_attempts']=state.get('pi_attempts',0)+1
                        state['phase']='RECOVERY_REVIEW' if ok else 'NEEDS_PI'
                        incident(state,'Pi recovery '+('completed: ' if ok else 'unavailable: ')+output)
                # A blocked task remains owned until positive reconciliation.
            elif state.get('phase') == 'RECOVERY_REVIEW':
                check_environment(config)
                resume_after_recovery(config, state)
            else:
                tick(config,state)
            save(state)
            print(json.dumps(read_status(state), ensure_ascii=True))
        except Exception as exc:
            state=load(STATE,new_state(config))
            queue_pi(state,type(exc).__name__+': '+str(exc))
            save(state)
            print(json.dumps(read_status(state),ensure_ascii=True))
            raise
        finally:
            lock.seek(0)
            msvcrt.locking(lock.fileno(),msvcrt.LK_UNLCK,1)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=('once','status','pause','resume'))
    args = parser.parse_args()
    config = load(CONFIG)
    if args.action == 'status':
        print(json.dumps(read_status(load(STATE,new_state(config))),indent=2))
    elif args.action in ('pause','resume'):
        state=load(STATE,new_state(config))
        state['phase']='MANUAL_HOLD' if args.action == 'pause' else ('ACTIVE' if state.get('active') else 'IDLE')
        state['reason']='Operator '+args.action
        save(state)
        print(state['phase'])
    else:
        supervise_once()

if __name__ == '__main__':
    main()
