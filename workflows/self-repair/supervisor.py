def now():
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')

def load(path, default=None):
    return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else default

def atomic(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + '.new')
    tmp.write_text(content, encoding='utf-8')
    os.replace(tmp, path)

def api(method, url, payload=None, key=None):
    data = json.dumps(payload).encode() if payload is not None else None
    headers = {'Content-Type': 'application/json'}
    if key: headers['Idempotency-Key'] = key
    with urlopen(Request(API + url, data=data, headers=headers, method=method), timeout=8) as response:
        return json.load(response)

def key_for(config, seq, kind):
    return hashlib.sha256(f"{config['campaign_id']}:{seq}:{kind}".encode()).hexdigest()[:36]

def save(state):
    state['updated_at'] = now()
    atomic(STATE, json.dumps(state, indent=2, ensure_ascii=True) + '\n')
    active = state.get('active') or {}
    lines = ['# G6 CDPA Self Repair - Live Progress', '',
             'Generated by the G6 Pi supervisor, not a source of truth.', '',
             f"- Updated UTC: {state['updated_at']}",
             f"- Campaign: {state.get('campaign')}",
             f"- Phase: {state.get('phase')}",
             f"- Current slice: {active.get('slice_id', 'none')}",
             f"- Current team: {active.get('team', 'none')}",
             f"- Current task id: {active.get('task_id', 'unconfirmed')}",
             f"- Task status/action: {active.get('status', 'unknown')}/{active.get('action', 'unknown')}",
             f"- Release: {state.get('release', 'NOT_ACCEPTED')}",
             f"- Reason: {state.get('reason', '')}", '', '## Completed slices']
    lines += ['- ' + x['slice_id'] + ': ' + str(x.get('evidence', '')) for x in state.get('completed', [])]
    lines += ['', '## Last incident', str(state.get('incident', 'none')), '']
    atomic(PROGRESS, '\n'.join(lines))

