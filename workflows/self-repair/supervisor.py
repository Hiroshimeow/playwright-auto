def incident(state, message):
    state['incident'] = now() + ' ' + str(message)[:400]
    state['reason'] = str(message)[:250]

def check_environment(config, *, allow_source_drift=False):
    if socket.gethostname().upper() != HOST or ROOT.resolve() != Path(config['repository']).resolve():
        raise RuntimeError('G6 repo identity mismatch')
    h = api('GET', '/health')
    if not all(h.get(k) for k in ('ok', 'worker_online', 'worker_ready', 'worker_runtime_ready', 'worker_command_loop_ready')):
        raise RuntimeError('CDPA worker not ready')
    if h.get('worker_source_drift', {}).get('drifted') and not allow_source_drift:
        raise RuntimeError('Worker source drift; safe drain/reload required')
    browser = api('GET', '/api/state')['browser']
    match = [e for e in browser.get('endpoints', []) if e.get('endpoint_id') == config['browser_endpoint_id']]
    if len(match) != 1 or not match[0].get('connected') or match[0].get('cdp_url') != 'http://127.0.0.1:9202':
        raise RuntimeError('Wrong or offline browser endpoint')
    return h

def verify_receipt(active):
    p = HERE / 'receipts' / (active['slice_id'] + '.json')
    d = load(p)
    if not isinstance(d, dict) or d.get('task_id') != active.get('task_id') or d.get('slice_id') != active['slice_id']:
        raise RuntimeError('Missing/mismatched receipt ' + str(p))
    if d.get('status') != 'PASS' or not d.get('tests') or not d.get('evidence'):
        raise RuntimeError('Receipt not evidence-backed PASS')
    return d

